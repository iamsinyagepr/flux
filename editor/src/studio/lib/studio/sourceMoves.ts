import { analyzeSource } from "./languageService";
import { formatSource } from "./formatter";
import {
  childrenOf,
  lex,
  parseSource,
  type Expr,
  type CallExpr,
} from "./parser";
import { constructorRegistry, type ReferenceEntry } from "./registry";
import type { SourceSelection } from "./sourceTree";

export type DropPlacement = "before" | "inside" | "after";
export interface SourceMove {
  source: string;
  selection: { from: number; to: number };
}
export interface SourceEditRequest extends SourceMove {
  before: string;
  documentId: string;
  nonce: number;
}
interface Location {
  node: CallExpr;
  parent?: CallExpr;
  param?: string;
  list?: Extract<Expr, { type: "list" }>;
}

/** Move source ranges rather than serializing the AST, preserving authored expressions/comments. */
export function moveSourceBlock(
  source: string,
  dragged: SourceSelection,
  target: SourceSelection,
  placement: DropPlacement,
  components: ReadonlyMap<string, ReferenceEntry> = new Map(),
  currentComponent?: string,
): SourceMove {
  if (dragged.documentId !== target.documentId)
    throw new Error("Move blocks within the same page or component file.");
  const parsed = parseSource(source);
  if (!parsed.root || parsed.diagnostics.length)
    throw new Error("Fix the source syntax before moving blocks.");
  const locations: Location[] = [];
  function walk(
    node: Expr,
    parent?: CallExpr,
    param?: string,
    list?: Location["list"],
  ) {
    if (node.type === "call") {
      locations.push({ node, parent, param, list });
      for (const [key, child] of Object.entries(node.args))
        walk(child, node, key);
      node.positional.forEach((child) => walk(child, node));
    } else if (node.type === "list") {
      node.items.forEach((child) => walk(child, parent, param, node));
    } else childrenOf(node).forEach((child) => walk(child, parent, param));
  }
  walk(parsed.root);
  const find = (range: SourceSelection) =>
    locations.find(
      ({ node }) => node.from === range.from && node.to === range.to,
    );
  const origin = find(dragged),
    destination = find(target);
  if (!origin || !destination)
    throw new Error("The source changed. Start the move again.");
  const definition = (node: CallExpr) =>
    (node.name === currentComponent && constructorRegistry.has(node.name)
      ? constructorRegistry.get(node.name)
      : components.get(node.name)) ?? constructorRegistry.get(node.name);
  const widget = (node: CallExpr) =>
    [
      "Layout",
      "Content",
      "Behavior",
      "Composition",
      "Storefront",
      "Storefront controls",
      "Forms",
      "Components",
      "Library",
    ].includes(definition(node)?.group ?? "");
  if (!widget(origin.node) || !widget(destination.node))
    throw new Error("Only component blocks can be moved.");
  if (target.from >= dragged.from && target.to <= dragged.to)
    throw new Error(
      "A block cannot be moved into itself or one of its children.",
    );
  // A call is movable only from a widget slot/list, never from an action or value expression.
  const originType =
    origin.parent && definition(origin.parent)?.parameters[origin.param ?? ""];
  if (!originType || !["Widget", "List<Widget>"].includes(originType))
    throw new Error(
      "This block is part of an expression and cannot be moved separately.",
    );
  let slot: string | undefined;
  let list: Location["list"];
  let index = 0;
  if (placement !== "inside") {
    if (
      !destination.list ||
      !destination.parent ||
      definition(destination.parent)?.parameters[destination.param ?? ""] !==
        "List<Widget>"
    )
      throw new Error(
        "Drop inside a wrapper, or beside a block in a children list.",
      );
    list = destination.list;
    index =
      list.items.indexOf(destination.node) + (placement === "after" ? 1 : 0);
  } else {
    const parameters = definition(destination.node)?.parameters ?? {};
    slot =
      parameters.children === "List<Widget>"
        ? "children"
        : parameters.child === "Widget"
          ? "child"
          : undefined;
    if (!slot)
      throw new Error(
        "This block has no children or child slot. Choose a layout wrapper.",
      );
    const contents = destination.node.args[slot];
    if (slot === "children") {
      if (contents && contents.type !== "list")
        throw new Error(
          "This children list is generated by an expression. Edit that expression in source.",
        );
      list = contents as Location["list"];
      index = list?.items.length ?? 0;
    } else if (
      contents &&
      !(
        contents.type === "call" &&
        contents.name === "SizedBox" &&
        !Object.keys(contents.args).length
      )
    ) {
      throw new Error(
        "This wrapper already has a child. Drop into its inner layout instead.",
      );
    }
  }
  const tokens = lex(source);
  const commaBetween = (from: number, to: number) =>
    tokens.find(
      (token) => token.from >= from && token.to <= to && token.text === ",",
    );
  const block = source.slice(origin.node.from, origin.node.to);
  const edits: {
    from: number;
    to: number;
    text: string;
    inserted?: boolean;
  }[] = [];
  if (origin.list) {
    const i = origin.list.items.indexOf(origin.node);
    if (list === origin.list && (index === i || index === i + 1))
      throw new Error("This block is already in that position.");
    const next = origin.list.items[i + 1],
      previous = origin.list.items[i - 1];
    const trailing = commaBetween(
      origin.node.to,
      next?.from ?? origin.list.to - 1,
    );
    const preceding = previous && commaBetween(previous.to, origin.node.from);
    edits.push({ from: origin.node.from, to: origin.node.to, text: "" });
    // Remove punctuation separately so adjacent comments stay intact.
    if (trailing)
      edits.push({ from: trailing.from, to: trailing.to, text: "" });
    else if (preceding)
      edits.push({ from: preceding.from, to: preceding.to, text: "" });
  } else {
    // Keep required widget slots valid and visible as an empty slot in the tree.
    edits.push({
      from: origin.node.from,
      to: origin.node.to,
      text: "SizedBox()",
    });
  }
  if (list) {
    const next = list.items[index];
    if (next)
      edits.push({
        from: next.from,
        to: next.from,
        text: block + ",\n",
        inserted: true,
      });
    else {
      const last = list.items.at(-1);
      const trailing = last && commaBetween(last.to, list.to - 1);
      edits.push({
        from: list.to - 1,
        to: list.to - 1,
        text: (last && !trailing ? "," : "") + "\n" + block + ",\n",
        inserted: true,
      });
    }
  } else if (slot) {
    const contents = destination.node.args[slot];
    if (contents)
      edits.push({
        from: contents.from,
        to: contents.to,
        text: block,
        inserted: true,
      });
    else {
      const end = destination.node.to - 1;
      const last = tokens
        .filter(
          (token) => token.from > destination.node.from && token.to <= end,
        )
        .at(-1);
      const prefix = last?.text === "(" || last?.text === "," ? "" : ",";
      edits.push({
        from: end,
        to: end,
        text:
          prefix +
          "\n" +
          slot +
          ": " +
          (slot === "children" ? "[\n" + block + ",\n]" : block) +
          ",\n",
        inserted: true,
      });
    }
  }
  let updated = source,
    insertedAt = 0;
  // Apply simultaneous source coordinates, with insertions before removals at the same boundary.
  edits.sort((a, b) => a.from - b.from || a.to - b.to);
  let offset = 0;
  for (const edit of edits) {
    const from = edit.from + offset,
      to = edit.to + offset;
    updated = updated.slice(0, from) + edit.text + updated.slice(to);
    if (edit.inserted) insertedAt = from + edit.text.indexOf(block);
    else if (from < insertedAt) insertedAt += edit.text.length - (to - from);
    offset += edit.text.length - (edit.to - edit.from);
  }
  const formatted = formatSource(updated);
  const errors = analyzeSource(
    formatted,
    components,
    currentComponent,
  ).diagnostics.filter((item) => item.severity === "error");
  if (errors.length) throw new Error("Cannot move here: " + errors[0].message);
  const tokenIndex = lex(updated).findIndex(
    (token) => token.from === insertedAt,
  );
  const from = lex(formatted)[tokenIndex]?.from;
  if (from === undefined)
    throw new Error(
      "Could not select the moved block. The source was not changed.",
    );
  return {
    source: formatted,
    selection: { from, to: from + origin.node.name.length },
  };
}

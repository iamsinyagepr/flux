// robots.txt and a sitemap of the pages without parameters. Pages with them
// (a product's) are found by following the site's own links.
func robotsAndSitemap(in Input) (robots, sitemap string) {
	var meta struct {
		SiteURL   string `json:"site_url"`
		Indexable *bool  `json:"indexable"`
	}
	_ = json.Unmarshal(in.Site, &meta)
	site := strings.TrimRight(meta.SiteURL, "/")
	if !strings.HasPrefix(site, "https://") {
		site = ""
	}
	indexable := meta.Indexable == nil || *meta.Indexable
	robots = "User-agent: *\n"
	if indexable {
		robots += "Allow: /\n"
	} else {
		robots += "Disallow: /\n"
	}
	if site == "" || !indexable {
		return robots, ""
	}
	robots += "\nSitemap: " + site + "/sitemap.xml\n"
	var urls []string
	for _, page := range in.Pages {
		if strings.Contains(page.Path, "$") {
			continue
		}
		// Left out: its SEO says so (sitemap: false), or it's not to be indexed.
		if page.SEO != nil && ((page.SEO.Sitemap != nil && !*page.SEO.Sitemap) || (page.SEO.Index != nil && !*page.SEO.Index)) {
			continue
		}
		urls = append(urls, "  <url><loc>"+htmlEscape(site+page.Path)+"</loc></url>")
	}
	sitemap = "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<urlset xmlns=\"http://www.sitemaps.org/schemas/sitemap/0.9\">\n" +
		strings.Join(urls, "\n") + "\n</urlset>\n"
	return robots, sitemap
}


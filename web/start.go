// libraryPackages are the Library's npm packages (pinned), by what in the
// runtime needs them: a site that doesn't play an animation doesn't install
// lottie-web.
var libraryPackages = map[string][2]string{
	"lottie-web/build/player/lottie_light": {"lottie-web", "5.13.0"},
}

// libraryDependencies is the Library's packages a site's files use.
func libraryDependencies(files []File) map[string]string {
	extra := map[string]string{}
	for marker, pkg := range libraryPackages {
		for _, f := range files {
			if strings.Contains(f.Content, marker) {
				extra[pkg[0]] = pkg[1]
				break
			}
		}
	}
	return extra
}

func packageJSON(name string, extra map[string]string) string {
	slug := strings.Trim(nonSlug.ReplaceAllString(strings.ToLower(name), "-"), "-")
	if slug == "" {
		slug = "storefront"
	}
	value := map[string]any{
		"name": slug, "private": true, "version": "1.0.0", "type": "module",
		"scripts": map[string]string{
			"dev": "vite dev",
			// Vite first: it writes the route tree the type check reads.
			"build":     "vite build && tsc --noEmit",
			"start":     "node server.mjs",
			"typecheck": "tsc --noEmit",
		},
		"dependencies":    withPackages(dependencies, extra),
		"devDependencies": devDependencies,
		// One copy of TanStack Query for the app and its SSR integration.
		"overrides": map[string]string{"@tanstack/query-core": dependencies["@tanstack/query-core"]},
	}
	raw, _ := json.MarshalIndent(value, "", "  ")
	return string(raw) + "\n"
}

// routeFile is a page's route module, in src/routes.
func routeFile(page dart.Page) string { return "page-" + strings.ToLower(page.ID) + ".tsx" }

// siteData is whether any page has data, and whether any of it is sent
// with a secret (the apps fetch that through the site's /studio-data).
func siteData(pages []dart.Page) (data, secrets bool) {
	for _, page := range pages {
		for _, imp := range page.Data {
			// The signed-in customer's is the browser's to fetch, not the server's.
			if signedInData(imp) {
				continue
			}
			data = true
			if imp.Secret != "" {
				secrets = true
			}
		}
	}
	return data, secrets
}

func viteConfig(pages []dart.Page, entry dart.Page, secrets bool) string {
	var routes []string
	for _, page := range pages {
		routes = append(routes, "        route("+q(page.Path)+", "+q(routeFile(page))+"),")
	}
	if entry.Path != "/" && !strings.Contains(entry.Path, "$") {
		routes = append(routes, "        route(\"/\", "+q(homeRouteFile)+"),")
	}
	if secrets {
		// The apps' way to a page import that needs this site's secrets.
		routes = append(routes, "        route(\"/studio-data/$page/$name\", \"studio-data.ts\"),")
	}
	return `// Generated by Upskale Studio.
import { defineConfig } from "vite";
import { tanstackStart } from "@tanstack/react-start/plugin/vite";
import { rootRoute, route } from "@tanstack/virtual-file-routes";
import viteReact from "@vitejs/plugin-react";

export default defineConfig(({ command }) => ({
  // A build is one self-contained server bundle: the site runs on Node, no
  // node_modules. The dev server loads packages from node_modules instead
  // (its module runner can't evaluate CommonJS packages such as React).
  ssr: command === "build" ? { noExternal: true } : {},
  plugins: [
    tanstackStart({
      router: {
        // A route per page, each at its own path (never nested in another).
        virtualRouteConfig: rootRoute("__root.tsx", [
` + strings.Join(routes, "\n") + `
        ]),
      },
    }),
    viteReact(),
  ],
}));
`
}

func routerTSX(in Input, entry dart.Page) string {
	var paths []string
	imports := make([][]pagedata.Import, len(in.Pages))
	for i, page := range in.Pages {
		paths = append(paths, "      "+q(page.ID)+": "+q(page.Path)+",")
		imports[i] = page.Data
	}
	// What the pages fetch themselves: the runtime doesn't load it site-wide.
	var own []string
	for _, resource := range []string{"menu", "cities"} {
		if pagedata.ImportsResource(imports, resource) {
			own = append(own, q(resource))
		}
	}
	return `// Generated by Upskale Studio. The router: made once in the browser, once
// per request on the server.
import { QueryClient } from "@tanstack/react-query";
import { createRouter } from "@tanstack/react-router";
import { setupRouterSsrQueryIntegration } from "@tanstack/react-router-ssr-query";
import { routeTree } from "./routeTree.gen";
import * as rt from "./studio/runtime";

export function getRouter() {
  const queryClient = new QueryClient({
    defaultOptions: { queries: { staleTime: 60_000, retry: 1 } },
  });
  rt.configure(
    {
      // The tenant API this site's stores, menus and orders come from.
      apiBaseUrl: ` + q(in.APIURL) + `,
      // A single-store site opens on this store; empty offers a choice.
      storeId: ` + q(in.StoreID) + `,
      // Where a visitor with nothing chosen yet starts.
      entryPath: ` + q(entry.Path) + `,
      // Route tokens (Route.cart …) open this project's own page paths.
      routePaths: {
` + strings.Join(paths, "\n") + `
      },
      // What the pages fetch themselves (their Data settings), so the site
      // doesn't load it for every page: a chosen store loads only the store.
      pageResources: [` + strings.Join(own, ", ") + `],
    },
    queryClient,
  );
  const router = createRouter({
    routeTree,
    context: { queryClient },
    defaultPreload: "intent",
    scrollRestoration: true,
    defaultNotFoundComponent: rt.NotFound,
    defaultErrorComponent: rt.PageError,
  });
  setupRouterSsrQueryIntegration({ router, queryClient });
  rt.useRouter(router);
  return router;
}

declare module "@tanstack/react-router" {
  interface Register {
    router: ReturnType<typeof getRouter>;
  }
}
`
}


// pageQueries is a page's data as TanStack Query reads it: one
// queryOptions per Data, each fetched through the site's server function
// (data.ts), so where it comes from, and any key it's sent with, stay on
// the server. Empty for a page without data.
func pageQueries(page dart.Page) string {
	fetched := 0
	for _, imp := range page.Data {
		if imp.Source != "client" {
			fetched++
		}
	}
	if fetched == 0 {
		return ""
	}
	var b strings.Builder
	b.WriteString("// Generated by Upskale Studio. This page's data (its Data settings), as\n" +
		"// TanStack Query fetches it. Edit the page's data instead.\n")
	b.WriteString("import { queryOptions } from \"@tanstack/react-query\";\n")
	public, signedIn := false, false
	for _, imp := range page.Data {
		if imp.Source == "client" {
			continue
		}
		if signedInData(imp) {
			signedIn = true
		} else {
			public = true
		}
	}
	if public {
		b.WriteString("import { fetchImport } from \"../data\";\n")
	}
	if signedIn {
		b.WriteString("import * as rt from \"../studio/runtime\";\n")
	}
	for _, imp := range page.Data {
		if imp.Source == "client" {
			continue
		}
		if signedInData(imp) {
			resource := pagedata.Resources[imp.Resource]
			var query []string
			for _, p := range resource.Params {
				if !p.InPath {
					query = append(query, q(p.Name))
				}
			}
			b.WriteString("\n/** " + imp.Name + ": Tenant." + imp.Resource + ", the signed-in customer's: asked by the browser with\n" +
				" * their session (keyed by it, so signing in or out asks again), nothing without one. */\n")
			b.WriteString("export const " + queryName(imp.Name) + " = (params: Record<string, string>, session: string) =>\n" +
				"  queryOptions({\n" +
				"    queryKey: [" + q(page.ID) + ", " + q(imp.Name) + ", session, params],\n" +
				"    queryFn: () => rt.signedInRead(" + q(resource.Path) + ", [" + strings.Join(query, ", ") + "], params" + selectArg(imp) + "),\n" +
				"    staleTime: 30_000,\n" +
				"  });\n")
			continue
		}
		where := "on the server, rendered into the page"
		if imp.OnClient() {
			where = "in the browser, once the page is showing"
		}
		source := imp.URL
		if imp.Source == "tenant" {
			source = "Tenant." + imp.Resource
		}
		b.WriteString("\n/** " + imp.Name + ": " + source + ", fetched " + where + ". */\n")
		b.WriteString("export const " + queryName(imp.Name) + " = (params: Record<string, string>) =>\n" +
			"  queryOptions({\n" +
			"    queryKey: [" + q(page.ID) + ", " + q(imp.Name) + ", params],\n" +
			"    queryFn: () => fetchImport({ data: { page: " + q(page.ID) + ", name: " + q(imp.Name) + ", params } }),\n" +
			"    staleTime: 60_000,\n" +
			"  });\n")
	}
	return b.String()
}

// signedInData is whether a Data is the signed-in customer's (pagedata's Auth).
func signedInData(imp pagedata.Import) bool {
	return imp.Source == "tenant" && pagedata.Resources[imp.Resource].Auth
}

// selectArg is a signed-in read's selection, the part of the answer it keeps.
func selectArg(imp pagedata.Import) string {
	if imp.Select == "" {
		return ""
	}
	return ", " + q(imp.Select)
}

// jsName is a Data's name as a JavaScript variable (it's a Flux name, so
// one already, but never one of the route's own).
func jsName(name string) string {
	clean := regexp.MustCompile(`[^A-Za-z0-9_$]`).ReplaceAllString(name, "_")
	if clean == "" || (clean[0] >= '0' && clean[0] <= '9') {
		clean = "_" + clean
	}
	return "d_" + clean
}

func queryName(name string) string {
	return strings.TrimPrefix(jsName(name), "d_") + "Query"
}

// queriesFile is where a page's queries are: src/queries/<page>.ts.
func queriesFile(page dart.Page) string { return strings.ToLower(page.ID) }

// pageRoute is a page's route module: its loader (its server Data, in order,
// one able to read another), its head (SEO, from that data), and its
// component, which asks for its client Data with useQuery.
func (e *emitter) pageRoute(page dart.Page, padded bool) string {
	var server, client, own []pagedata.Import
	where := map[string]string{} // a Data's name → "server" or "client"
	for _, imp := range page.Data {
		if imp.Source == "client" {
			// The customer's own: never fetched, followed as it changes.
			own = append(own, imp)
			where[imp.Name] = "client"
			continue
		}
		if signedInData(imp) && !imp.OnClient() {
			e.fail(&cdsl.Expr{}, "Data "+imp.Name+" is the signed-in customer's (Tenant."+imp.Resource+"): only the browser has their session, so it goes in usingClient.")
		}
		if imp.OnClient() {
			client = append(client, imp)
			where[imp.Name] = "client"
		} else {
			server = append(server, imp)
			where[imp.Name] = "server"
		}
	}
	e.clientData = map[string]bool{}
	for _, imp := range client {
		e.clientData[imp.Name] = true
	}
	// A parameter's value, where it's computed: the loader (server) or the
	// component (client). An earlier server Data is the loader's variable in
	// one and the loader's answer in the other.
	value := func(imp pagedata.Import, p pagedata.Param, inComponent bool) string {
		switch p.From {
		case "route":
			return "params[" + q(p.Value) + "]"
		case "query":
			if p.Fallback != nil {
				// Its search param's default, when the address has none.
				return "(search[" + q(p.Value) + "] ?? " + q(*p.Fallback) + ")"
			}
			return "search[" + q(p.Value) + "]"
		case "store":
			return "rt.siteStore()"
		case "import":
			name, path, _ := strings.Cut(p.Value, ".")
			if where[name] == "client" && !imp.OnClient() {
				e.fail(&cdsl.Expr{}, "Data "+imp.Name+" is fetched on the server, but reads "+name+", fetched in the browser: fetch "+name+` on the server too (fetch: "server").`)
			}
			target := jsName(name)
			if inComponent && where[name] == "server" {
				// The loader's answer, by the Data's own name.
				target = "server[" + q(name) + "]"
			}
			if path == "" {
				return target
			}
			return "rt.read(" + target + ", " + pathList(strings.Split(path, ".")) + ")"
		}
		return q(p.Value)
	}
	paramsOf := func(imp pagedata.Import, inComponent bool) string {
		var fields []string
		for _, p := range imp.Params {
			fields = append(fields, q(p.Name)+": "+value(imp, p, inComponent))
		}
		return "rt.params({ " + strings.Join(fields, ", ") + " })"
	}
	ready := func(imp pagedata.Import, params string) string {
		var checks []string
		for _, name := range pagedata.RequiredParams(imp) {
			checks = append(checks, params+"["+q(name)+"]")
		}
		return strings.Join(checks, " && ")
	}
	reads := func(imps []pagedata.Import, from string) bool {
		for _, imp := range imps {
			for _, p := range imp.Params {
				if p.From == from {
					return true
				}
			}
		}
		return false
	}

	var b strings.Builder
	b.WriteString("// Generated by Upskale Studio. Edit the page's Data and SEO settings instead.\n")
	b.WriteString("import { createFileRoute } from \"@tanstack/react-router\";\n")
	if len(client) > 0 {
		b.WriteString("import { useQuery } from \"@tanstack/react-query\";\n")
	}
	if len(client)+len(own) > 0 {
		b.WriteString("import { useMemo } from \"react\";\n")
	}
	b.WriteString("import * as rt from \"../studio/runtime\";\n")
	if len(server)+len(client) > 0 {
		var names []string
		for _, imp := range page.Data {
			if imp.Source != "client" {
				names = append(names, queryName(imp.Name))
			}
		}
		b.WriteString("import { " + strings.Join(names, ", ") + " } from " + q("../queries/"+queriesFile(page)) + ";\n")
	}
	b.WriteString("import { " + e.def.name + " } from " + q("../pages/"+strings.TrimSuffix(e.def.file[len("src/pages/"):], ".tsx")) + ";\n\n")

	b.WriteString("export const Route = createFileRoute(" + q(page.Path) + ")({\n")
	if len(server) > 0 {
		// Server Data, in order: each awaited before the page renders, so
		// it's in the HTML (and its head); one without what it needs (no
		// store chosen yet) is left out, and drawn without.
		args := []string{"context: { queryClient }"}
		if reads(server, "route") {
			args = append(args, "params")
		}
		if reads(server, "query") {
			args = append(args, "location")
		}
		b.WriteString("  loader: async ({ " + strings.Join(args, ", ") + " }) => {\n")
		if reads(server, "query") {
			b.WriteString("    const search = location.search as Record<string, unknown>;\n")
		}
		var names []string
		for _, imp := range server {
			v := jsName(imp.Name)
			p := v + "Params"
			fetch := "await queryClient.ensureQueryData(" + queryName(imp.Name) + "(" + p + ")).catch(rt.notFoundOn404)"
			b.WriteString("    const " + p + " = " + paramsOf(imp, false) + ";\n")
			if check := ready(imp, p); check != "" {
				fetch = check + " ? " + fetch + " : null"
			}
			b.WriteString("    const " + v + " = " + fetch + ";\n")
			names = append(names, q(imp.Name)+": "+v)
		}
		b.WriteString("    return { " + strings.Join(names, ", ") + " };\n  },\n")
		b.WriteString("  head: ({ loaderData, match }) => rt.pageHead(match.pathname, " + e.seoFields(page.SEO) + ", loaderData),\n")
	} else {
		b.WriteString("  head: ({ match }) => rt.pageHead(match.pathname, " + e.seoFields(page.SEO) + ", undefined),\n")
	}
	b.WriteString("  component: Page,\n});\n\n")

	b.WriteString("function Page() {\n")
	data := ""
	if len(server) > 0 {
		b.WriteString("  const server = Route.useLoaderData();\n")
		data = "server"
	}
	if len(client)+len(own) > 0 {
		if reads(client, "route") {
			b.WriteString("  const params = Route.useParams() as Record<string, string>;\n")
		}
		if reads(client, "query") {
			b.WriteString("  const search = Route.useSearch() as Record<string, unknown>;\n")
		}
		// Client Data: asked for in the browser, shown when it comes (empty
		// until then, as on the server's render).
		var fields, deps []string
		if len(server) > 0 {
			fields = append(fields, "...server")
			deps = append(deps, "server")
		}
		for _, imp := range own {
			v := jsName(imp.Name)
			b.WriteString("  const " + v + " = rt.useClient(" + q(imp.Resource) + ");\n")
			fields = append(fields, q(imp.Name)+": "+v)
			deps = append(deps, v)
		}
		signedIn := false
		for _, imp := range client {
			signedIn = signedIn || signedInData(imp)
		}
		if signedIn {
			// Who's signed in: their data is asked for again when it changes.
			b.WriteString("  const session = rt.useSession();\n")
		}
		for _, imp := range client {
			v := jsName(imp.Name)
			p := v + "Params"
			b.WriteString("  const " + p + " = " + paramsOf(imp, true) + ";\n")
			options := queryName(imp.Name) + "(" + p + ")"
			if signedInData(imp) {
				options = queryName(imp.Name) + "(" + p + ", session)"
			}
			if check := ready(imp, p); check != "" {
				options = "{ ..." + options + ", enabled: Boolean(" + check + ") }"
			}
			b.WriteString("  const " + v + " = useQuery(" + options + ").data ?? null;\n")
			fields = append(fields, q(imp.Name)+": "+v)
			deps = append(deps, v)
		}
		b.WriteString("  const data = useMemo(() => ({ " + strings.Join(fields, ", ") + " }), [" + strings.Join(deps, ", ") + "]);\n")
		data = "data"
	}
	dataProp := ""
	if data != "" {
		dataProp = " data={" + data + "}"
	}
	b.WriteString("  return (\n" +
		"    <rt.Page id=" + q(page.ID) + " pattern=" + q(page.Path) + " padded={" + boolString(padded) + "}" + dataProp + ">\n" +
		"      <" + e.def.name + " />\n    </rt.Page>\n  );\n}\n")
	return b.String()
}

func boolString(v bool) string {
	if v {
		return "true"
	}
	return "false"
}

// seoFields is a page's SEO as a function of its data (b): each field a
// Flux expression compiled like the page's own.
func (e *emitter) seoFields(seo *pagedata.SEO) string {
	if seo == nil {
		return "() => ({})"
	}
	var fields []string
	field := func(name, source string) {
		source = strings.TrimSpace(source)
		if source == "" {
			return
		}
		node, problem := cdsl.ParseExpression(source)
		if problem != nil {
			e.fail(&cdsl.Expr{}, "SEO "+name+": "+problem.Message)
		}
		var outside func(n *cdsl.Expr)
		outside = func(n *cdsl.Expr) {
			if n == nil {
				return
			}
			if n.Kind == cdsl.Ref {
				head := strings.Split(n.Name, ".")[0]
				switch head {
				case "state", "options", "event", "input":
					e.fail(n, "SEO "+name+" reads "+n.Name+": only the page's data and the store are known when it's rendered.")
				}
				if e.clientData[head] {
					e.fail(n, "SEO "+name+" reads "+head+", fetched in the browser: the page's head is made on the server, so fetch "+head+` there (fetch: "server").`)
				}
			}
			for _, child := range cdsl.Children(n) {
				outside(child)
			}
		}
		outside(node)
		fields = append(fields, name+": rt.text("+e.expr(node, scope{options: "{}", aliases: map[string]string{}})+")")
	}
	field("title", seo.Title)
	field("description", seo.Description)
	field("image", seo.Image)
	if seo.Schema != "" {
		fields = append(fields, "schema: "+q(seo.Schema), "subject: "+q(seo.Subject))
	}
	if seo.Index != nil && !*seo.Index {
		// Not for search engines: <meta name="robots" content="noindex">.
		fields = append(fields, "noindex: true")
	}
	if len(fields) == 0 {
		return "() => ({})"
	}
	return "(b) => ({ " + strings.Join(fields, ", ") + " })"
}

// dataServerTS is where every page import comes from, server only: never
// in the browser's bundle.
func dataServerTS(in Input, fields map[string]map[string]any) string {
	type spec struct {
		Source       string   `json:"source"`
		Path         string   `json:"path,omitempty"`
		Query        []string `json:"query,omitempty"`
		URL          string   `json:"url,omitempty"`
		Select       string   `json:"select,omitempty"`
		Secret       string   `json:"secret,omitempty"`
		SecretHeader string   `json:"secretHeader,omitempty"`
		Fields       any      `json:"fields,omitempty"`
	}
	table := map[string]map[string]spec{}
	for _, page := range in.Pages {
		if len(page.Data) == 0 {
			continue
		}
		table[page.ID] = map[string]spec{}
		for _, imp := range page.Data {
			if signedInData(imp) || imp.Source == "client" {
				// The browser asks for it, with the visitor's session; or it's
				// the visitor's own, never fetched.
				continue
			}
			s := spec{Source: imp.Source, Select: imp.Select}
			if imp.Source == "tenant" {
				resource := pagedata.Resources[imp.Resource]
				s.Path = resource.Path
				for _, p := range resource.Params {
					if !p.InPath {
						s.Query = append(s.Query, p.Name)
					}
				}
			} else {
				s.URL, s.Secret, s.SecretHeader = imp.URL, imp.Secret, imp.SecretHeader
			}
			if f, ok := fields[page.ID][imp.Name]; ok {
				s.Fields = f
			}
			table[page.ID][imp.Name] = s
		}
	}
	raw, _ := json.MarshalIndent(table, "", "  ")
	return `// Generated by Upskale Studio. Every page import is fetched here, on the
// server: where it comes from, and any key it's sent with, stay out of the
// browser. Secrets are the website's environment variables (SECRET_<NAME>).
// Used by the pages' server function (data.ts) and by /studio-data, where
// the apps fetch the imports that need a secret (routes/studio-data.ts).
import { fetchSpec, project, type FetchSpec } from "./studio/fetch.server";

// The tenant API: the deployment's own (TENANT_API), or the one built against.
const TENANT_API = ` + q(in.APIURL) + `;

const IMPORTS: Record<string, Record<string, FetchSpec>> = ` + string(raw) + `;

/** One page import, or null when the page imports nothing by that name. */
export function importSpec(page: string, name: string): FetchSpec | null {
  return Object.hasOwn(IMPORTS, page) && Object.hasOwn(IMPORTS[page], name) ? IMPORTS[page][name] : null;
}

/**
 * One page import, fetched. For the page (trim): only the fields its code
 * reads (fields), the rest of each record never leaves the server. The apps
 * (/studio-data) get it whole: they're built from the page, not limited to it.
 */
export async function fetchPageImport(page: string, name: string, params: Record<string, string>, trim = false) {
  const spec = importSpec(page, name);
  if (!spec) throw new Error("404: no such import: " + page + "/" + name);
  const value = await fetchSpec(spec, params, process.env.TENANT_API || TENANT_API);
  return trim ? project(value, spec.fields) : value;
}
`
}


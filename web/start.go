// rootedPages are the pages with the start page's at the root: the page
// that had "/" moves to "/<its id>" (or "/<its id>-page" if that's taken),
// so links to it still lead somewhere, and the start page answers at "/"
// as well (homeRoute). A start page with $params, or one already at "/",
// changes nothing.
func rootedPages(pages []dart.Page, entry dart.Page) ([]dart.Page, dart.Page) {
	if entry.Path == "/" || strings.Contains(entry.Path, "$") {
		return pages, entry
	}
	taken := map[string]bool{}
	for _, page := range pages {
		taken[page.Path] = true
	}
	out := make([]dart.Page, len(pages))
	for i, page := range pages {
		if page.Path == "/" {
			moved := "/" + page.ID
			if taken[moved] {
				moved += "-page"
			}
			page.Path = moved
		}
		out[i] = page
	}
	return out, entry
}

// withPackages is the site's dependencies and the Library's it uses.
func withPackages(base, extra map[string]string) map[string]string {
	if len(extra) == 0 {
		return base
	}
	all := make(map[string]string, len(base)+len(extra))
	for name, version := range base {
		all[name] = version
	}
	for name, version := range extra {
		all[name] = version
	}
	return all
}
